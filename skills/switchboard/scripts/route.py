#!/usr/bin/env python3
"""Pick the skills a request needs, and keep the slash commands in step. Standard library only.

    route.py "add an endpoint and its screen"     the skills that fit, and why
    route.py hook                                 Claude Code UserPromptSubmit hook (JSON on stdin)
    route.py --list                               every installed skill and its short names
    route.py --resolve                            prove every skill and every /short resolves (exit 1 if not)
    route.py --write [--commands-dir DIR]         write <short>.md slash commands (and the AGENTS.md table, if marked)
    route.py --check [--commands-dir DIR]         exit 1 when skills.toml, the commands or AGENTS.md are stale
    --no-commands                                 with --write/--check: leave slash commands out (no Claude Code)

A request names a skill with @<short> or @<skill> anywhere (`@api @seed add a project`), or, in
Claude Code, /<short> at the start (`/docs sync the docs`). Otherwise the triggers and paths in
skills.toml pick them. Only installed skills (folders beside this one with a SKILL.md) are picked.

Where things are: the skills folder is the one holding this skill (`.claude/skills`, `.agents/skills`,
`.trae/skills`, or `skills/` in the shipkit repository); the project is the folder above `.claude`,
`.agents` or `.trae` (or SHIPKIT_ROOT); commands go to <project>/.claude/commands (or the shipped
copy in switchboard/commands inside the shipkit repository).
"""

from __future__ import annotations

import fnmatch
import json
import os
import re
import sys
import tomllib
from dataclasses import dataclass, field
from pathlib import Path

HERE = Path(__file__).resolve().parent
SKILL = HERE.parent
SKILLS_DIR = SKILL.parent
INSTALLED = SKILLS_DIR.parent.name in (".claude", ".agents", ".trae")
ROOT = Path(os.environ["SHIPKIT_ROOT"]).resolve() if os.environ.get("SHIPKIT_ROOT") else (SKILLS_DIR.parents[1] if INSTALLED else SKILLS_DIR.parent)
COMMANDS_DIR = Path(os.environ["SHIPKIT_COMMANDS_DIR"]) if os.environ.get("SHIPKIT_COMMANDS_DIR") else (ROOT / ".claude" / "commands" if INSTALLED else SKILL / "commands")
AGENTS_MD = ROOT / "AGENTS.md"
TABLE_START = "<!-- shipkit:skills:start (generated by switchboard/scripts/route.py --write) -->"
TABLE_END = "<!-- shipkit:skills:end -->"
GENERATED = "# generated by the switchboard skill (route.py --write); edit switchboard/skills.toml"
MAX_PICKED = 4
# Claude Code's own commands; a short name must not hide one.
BUILT_IN = {
    "add-dir", "agents", "bashes", "bug", "clear", "code-review", "compact", "config", "context", "cost", "doctor",
    "exit", "export", "fast", "feedback", "help", "hooks", "ide", "init", "install-github-app", "login", "logout",
    "loop", "mcp", "memory", "model", "output-style", "permissions", "plan", "plugin", "pr-comments",
    "privacy-settings", "release-notes", "resume", "review", "rewind", "run", "sandbox", "schedule",
    "security-review", "simplify", "skills", "status", "statusline", "terminal-setup", "theme", "todos",
    "upgrade", "usage", "vim",
}  # fmt: skip


@dataclass
class Skill:
    name: str
    short: list[str]
    summary: str
    triggers: list[re.Pattern] = field(default_factory=list)
    paths: list[str] = field(default_factory=list)
    with_: list[str] = field(default_factory=list)


@dataclass
class Pick:
    skill: Skill
    why: list[str]
    named: bool = False
    companion_of: str | None = None


def installed() -> set[str]:
    return {p.parent.name for p in SKILLS_DIR.glob("*/SKILL.md")}


def load(path: Path = SKILL / "skills.toml", only_installed: bool = True) -> dict[str, Skill]:
    data = tomllib.loads(path.read_text())
    present = installed()
    skills: dict[str, Skill] = {}
    for name, entry in data.items():
        if only_installed and name not in present:
            continue
        skills[name] = Skill(
            name=name,
            short=list(entry.get("short", [])),
            summary=entry.get("summary", ""),
            triggers=[re.compile(t, re.IGNORECASE) for t in entry.get("triggers", [])],
            paths=list(entry.get("paths", [])),
            with_=list(entry.get("with", [])),
        )
    return skills


def by_handle(skills: dict[str, Skill]) -> dict[str, Skill]:
    handles: dict[str, Skill] = {}
    for skill in skills.values():
        handles[skill.name] = skill
        for short in skill.short:
            handles[short] = skill
    return handles


# ── picking ──────────────────────────────────────────────────────────────────

PATH_TOKEN = re.compile(r"[\w.@-]+(?:/[\w.@*-]+)+/?")


def named_in(text: str, skills: dict[str, Skill]) -> list[tuple[Skill, str]]:
    """@handle anywhere, or /handle at the very start (a Claude Code command)."""
    handles = by_handle(skills)
    found: list[tuple[Skill, str]] = []
    for match in re.finditer(r"(?:(?<=\s)|^)@([a-z][a-z0-9-]*)\b", text):
        if match.group(1) in handles:
            found.append((handles[match.group(1)], "@" + match.group(1)))
    start = re.match(r"\s*/([a-z][a-z0-9-]*)\b", text)
    if start and start.group(1) in handles:
        found.insert(0, (handles[start.group(1)], "/" + start.group(1)))
    return found


def route(text: str, skills: dict[str, Skill] | None = None) -> list[Pick]:
    skills = skills or load()
    picks: dict[str, Pick] = {}
    for skill, how in named_in(text, skills):
        picks.setdefault(skill.name, Pick(skill, [f"named ({how})"], named=True))

    scored: list[tuple[int, Pick]] = []
    tokens = [t.strip("`'\"()[],.:;") for t in PATH_TOKEN.findall(text)]
    for skill in skills.values():
        if skill.name in picks:
            continue
        why: list[str] = []
        for pattern in skill.triggers:
            match = pattern.search(text)
            if match:
                why.append(f'"{match.group(0).strip()}"')
        for token in tokens:
            if any(fnmatch.fnmatch(token, glob) or fnmatch.fnmatch(token.rstrip("/") + "/x", glob) for glob in skill.paths):
                why.append(token)
                break
        if why:
            scored.append((len(why), Pick(skill, why)))
    for _, pick in sorted(scored, key=lambda s: -s[0]):
        if len(picks) >= MAX_PICKED:
            break
        picks[pick.skill.name] = pick

    for pick in list(picks.values()):
        for other in pick.skill.with_:
            if other in skills and other not in picks:
                picks[other] = Pick(skills[other], [], companion_of=pick.skill.name)
    return list(picks.values())


def describe(picks: list[Pick]) -> str:
    lines = []
    for pick in picks:
        label = f"{pick.skill.name} ({pick.skill.short[0]})" if pick.skill.short else pick.skill.name
        if pick.companion_of:
            reason = f"goes with {pick.companion_of}"
        else:
            reason = ", ".join(pick.why[:3])
        lines.append(f"- {label}: {reason}")
    return "\n".join(lines)


def hook() -> int:
    """UserPromptSubmit: add the skills that fit as context for the model. Silent when none do."""
    try:
        event = json.load(sys.stdin)
    except json.JSONDecodeError:
        return 0
    prompt = event.get("prompt") or ""
    if not prompt.strip():
        return 0
    picks = route(prompt)
    if not picks:
        return 0
    named = any(p.named for p in picks)
    head = "Skills for this message (the switchboard skill):"
    tail = (
        "The user named the first. Load it with the Skill tool before starting; load the others that fit."
        if named
        else "Load the ones that fit with the Skill tool before starting; skip any that clearly do not."
    )
    context = f"{head}\n{describe(picks)}\n{tail}"
    print(json.dumps({"hookSpecificOutput": {"hookEventName": "UserPromptSubmit", "additionalContext": context}}))
    return 0


# ── generated files ──────────────────────────────────────────────────────────


def command_text(skill: Skill, short: str) -> str:
    summary = skill.summary.replace('"', "'")
    return (
        "---\n"
        f"{GENERATED}\n"
        f'description: "{skill.name}: {summary}"\n'
        'argument-hint: "[what to do]"\n'
        "---\n\n"
        f"Use the `{skill.name}` skill for this request: load it with the Skill tool "
        f"(or read `.claude/skills/{skill.name}/SKILL.md` or `.agents/skills/{skill.name}/SKILL.md`) and follow it.\n\n"
        "$ARGUMENTS\n"
    )


NO_COMMANDS = False  # --no-commands: an install without Claude Code keeps only the AGENTS.md table


def commands(skills: dict[str, Skill]) -> dict[Path, str]:
    if NO_COMMANDS:
        return {}
    return {COMMANDS_DIR / f"{short}.md": command_text(skill, short) for skill in skills.values() for short in skill.short}


def table(skills: dict[str, Skill]) -> str:
    rows = ["| Skill | Short | Use it for |", "|---|---|---|"]
    for skill in skills.values():
        shorts = ", ".join(f"`{s}`" for s in skill.short)
        rows.append(f"| `{skill.name}` | {shorts} | {skill.summary} |")
    return "\n".join([TABLE_START, *rows, TABLE_END])


def has_table(current: str) -> bool:
    return TABLE_START in current and TABLE_END in current


def agents_md(skills: dict[str, Skill], current: str) -> str:
    if not has_table(current):
        return current
    before, rest = current.split(TABLE_START, 1)
    _, after = rest.split(TABLE_END, 1)
    return before + table(skills) + after


def stale_commands(expected: dict[Path, str]) -> list[Path]:
    if NO_COMMANDS or not COMMANDS_DIR.exists():
        return []
    return [p for p in COMMANDS_DIR.glob("*.md") if p not in expected and GENERATED in p.read_text()]


def write(skills: dict[str, Skill]) -> list[str]:
    changed: list[str] = []
    expected = commands(skills)
    if expected:
        COMMANDS_DIR.mkdir(parents=True, exist_ok=True)
    for path, text in expected.items():
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
            changed.append(shown(path))
    for path in stale_commands(expected):
        path.unlink()
        changed.append(f"removed {shown(path)}")
    if AGENTS_MD.exists():
        current = AGENTS_MD.read_text()
        updated = agents_md(skills, current)
        if updated != current:
            AGENTS_MD.write_text(updated)
            changed.append("AGENTS.md")
    return changed


def shown(path: Path) -> str:
    try:
        return path.relative_to(ROOT).as_posix()
    except ValueError:
        return str(path)


def check(skills: dict[str, Skill]) -> list[str]:
    errors: list[str] = []
    on_disk = installed()
    known = set(load(only_installed=False))
    for name in sorted(on_disk - known):
        errors.append(f"{name}: a skill with no entry in skills.toml")
    for name in sorted(set(skills) - on_disk):
        errors.append(f"{name}: in skills.toml, but {SKILLS_DIR.name}/{name}/SKILL.md does not exist")
    seen: dict[str, str] = {}
    for skill in skills.values():
        if not skill.short:
            errors.append(f"{skill.name}: no short name")
        if not skill.summary:
            errors.append(f"{skill.name}: no summary")
        if not skill.triggers and not skill.paths:
            errors.append(f"{skill.name}: no triggers and no paths; it is never picked")
        for short in skill.short:
            if not re.fullmatch(r"[a-z][a-z0-9-]{1,11}", short):
                errors.append(f"{skill.name}: short name {short!r} is not 2-12 lowercase letters, digits, hyphens")
            if short in BUILT_IN:
                errors.append(f"{skill.name}: short name {short!r} hides Claude Code's /{short}")
            if short in skills and short != skill.name:
                errors.append(f"{skill.name}: short name {short!r} is another skill's name")
            if short in seen:
                errors.append(f"{skill.name}: short name {short!r} is also {seen[short]}'s")
            seen[short] = skill.name
        for other in skill.with_:
            if other not in skills:
                errors.append(f"{skill.name}: with names no skill ({other})")
    expected = commands(skills)
    for path, text in expected.items():
        if not path.exists() or path.read_text() != text:
            errors.append(f"{shown(path)} is stale; run route.py --write")
    for path in stale_commands(expected):
        errors.append(f"{shown(path)} names no short in skills.toml; run route.py --write")
    if AGENTS_MD.exists() and agents_md(skills, AGENTS_MD.read_text()) != AGENTS_MD.read_text():
        errors.append("AGENTS.md's skill table is stale; run route.py --write")
    return errors


def resolve_all(skills: dict[str, Skill]) -> tuple[list[str], bool]:
    """Every skill by @name, and every short name as /short and @short: the first pick must be that skill."""
    lines, ok = [], True
    for skill in skills.values():
        path = SKILLS_DIR / skill.name / "SKILL.md"
        probes = [f"@{skill.name} do it"] + [f"/{s} do it" for s in skill.short] + [f"@{s} do it" for s in skill.short]
        results = []
        for probe in probes:
            picks = route(probe, skills)
            hit = bool(picks) and picks[0].skill.name == skill.name and picks[0].named
            ok &= hit
            results.append(f"{probe.split()[0]} {'ok' if hit else 'FAIL'}")
        command = NO_COMMANDS or all((COMMANDS_DIR / f"{s}.md").exists() for s in skill.short)
        ok &= path.exists() and command
        lines.append(
            f"{skill.name:14} {'SKILL.md ok' if path.exists() else 'SKILL.md MISSING'}  "
            f"{('commands n/a' if NO_COMMANDS else 'commands ok') if command else 'commands MISSING'}  " + "  ".join(results)
        )
    return lines, ok


def main(argv: list[str]) -> int:
    global COMMANDS_DIR, NO_COMMANDS
    if "--no-commands" in argv:
        NO_COMMANDS = True
        argv = [a for a in argv if a != "--no-commands"]
    if "--commands-dir" in argv:
        at = argv.index("--commands-dir")
        COMMANDS_DIR = Path(argv[at + 1]).resolve()
        argv = argv[:at] + argv[at + 2 :]
    if not argv or argv[0] in ("-h", "--help"):
        print(__doc__)
        return 0
    if argv[0] == "hook":
        return hook()
    skills = load()
    if argv[0] == "--resolve":
        lines, ok = resolve_all(skills)
        print("\n".join(lines))
        print(f"\n{len(skills)} skills, {sum(len(s.short) for s in skills.values())} short names: {'every one resolves' if ok else 'FAILURES above'}")
        return 0 if ok else 1
    if argv[0] == "--list":
        for skill in skills.values():
            print(f"{', '.join(skill.short):14} {skill.name}")
        return 0
    if argv[0] == "--write":
        changed = write(skills)
        print("\n".join(changed) if changed else "Nothing to write")
        return 0
    if argv[0] == "--check":
        errors = check(skills)
        for error in errors:
            print(f"error: {error}")
        if not errors:
            print(f"{len(skills)} skills, {sum(len(s.short) for s in skills.values())} short names: in step")
        return 1 if errors else 0
    picks = route(" ".join(argv), skills)
    print(describe(picks) if picks else "No skill fits; the request may not need one.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
